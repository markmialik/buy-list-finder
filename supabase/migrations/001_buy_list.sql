-- Buy List Finder: tables + security rules.
-- Only accounts listed in public.app_users can read or change anything.
-- The public (anon) key alone can read nothing.

-- Helpers live in a schema the web API does not expose.
create schema if not exists private;
revoke all on schema private from public, anon;
grant usage on schema private to authenticated;

-- Who may use the app
create table public.app_users (
  user_id uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

create function private.is_app_user()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.app_users where user_id = (select auth.uid())
  );
$$;
revoke all on function private.is_app_user() from public, anon;
grant execute on function private.is_app_user() to authenticated;

create function private.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- One row per thing to buy
create table public.items (
  id bigint generated by default as identity primary key,

  -- What & where (owner)
  name        text not null default '',
  search_on   text not null default 'both'    check (search_on in ('both', 'ebay', 'facebook')),
  status      text not null default 'hunting' check (status in ('hunting', 'paused', 'bought')),
  priority    text not null default 'normal'  check (priority in ('high', 'normal', 'low')),

  -- Filters (owner)
  category    text,
  condition   text not null default 'any'     check (condition in ('any', 'new', 'used', 'for_parts')),
  min_price   numeric(10, 2) check (min_price >= 0),
  max_price   numeric(10, 2) check (max_price >= 0),
  distance_mi integer        check (distance_mi > 0),

  -- Rules + alerts (owner)
  what_counts text,
  ebay_alert  boolean not null default false,
  fb_alert    boolean not null default false,

  -- Prices
  my_target        numeric(10, 2) check (my_target >= 0),   -- owner
  suggested_target numeric(10, 2) check (suggested_target >= 0), -- agents
  usual_price      numeric(10, 2) check (usual_price >= 0),
  sold_low         numeric(10, 2) check (sold_low >= 0),
  sold_high        numeric(10, 2) check (sold_high >= 0),
  sales_found      integer        check (sales_found >= 0),
  confidence       text           check (confidence in ('high', 'medium', 'low')),
  research_notes   text,
  researched_at    timestamptz,
  researched_by    text,

  my_notes   text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint price_range check (min_price is null or max_price is null or min_price <= max_price)
);

create trigger items_set_updated_at
  before update on public.items
  for each row execute function private.set_updated_at();

-- App-wide settings: exactly one row
create table public.settings (
  id                   smallint primary key default 1 check (id = 1),
  home_zip             text check (home_zip ~ '^[0-9]{5}$'),
  fb_location_id       text,
  default_fb_radius_mi integer not null default 40 check (default_fb_radius_mi > 0),
  updated_at           timestamptz not null default now()
);
insert into public.settings (id) values (1);

create trigger settings_set_updated_at
  before update on public.settings
  for each row execute function private.set_updated_at();

-- Row Level Security
alter table public.app_users enable row level security;
alter table public.items     enable row level security;
alter table public.settings  enable row level security;

create policy "app users: see own membership" on public.app_users
  for select to authenticated
  using (user_id = (select auth.uid()));

create policy "items: app users read"   on public.items for select to authenticated using ((select private.is_app_user()));
create policy "items: app users add"    on public.items for insert to authenticated with check ((select private.is_app_user()));
create policy "items: app users change" on public.items for update to authenticated using ((select private.is_app_user())) with check ((select private.is_app_user()));
create policy "items: app users delete" on public.items for delete to authenticated using ((select private.is_app_user()));

create policy "settings: app users read"   on public.settings for select to authenticated using ((select private.is_app_user()));
create policy "settings: app users change" on public.settings for update to authenticated using ((select private.is_app_user())) with check ((select private.is_app_user()));

-- Table privileges: nothing for anon, only what the page needs for signed-in users
revoke all on public.app_users, public.items, public.settings from anon;
revoke all on public.app_users, public.items, public.settings from authenticated;
grant select                         on public.app_users to authenticated;
grant select, insert, update, delete on public.items     to authenticated;
grant select, update                 on public.settings  to authenticated;
grant usage on sequence public.items_id_seq to authenticated;
